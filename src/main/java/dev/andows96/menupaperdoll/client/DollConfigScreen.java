package dev.andows96.menupaperdoll.client;

import java.util.Set;
import net.minecraft.client.gui.screens.Screen;
import net.minecraft.network.chat.Component;
import net.neoforged.fml.ModContainer;
import net.neoforged.fml.config.ModConfig;
import net.neoforged.neoforge.client.gui.ConfigurationScreen;
import net.neoforged.neoforge.client.gui.ConfigurationScreen.ConfigurationSectionScreen;
import net.neoforged.neoforge.common.ModConfigSpec;

/**
 * NeoForge's standard configuration screen, with the automatic "Allowed Values: …" / "Default: …" /
 * "Range: …" comment lines stripped from the options that should not carry a hover description.
 *
 * <p>Those lines are generated by {@code ModConfigSpec} itself (they are not written by this mod), so
 * the only way to get rid of them without replacing the screen is to override the tooltip builder.
 * Everything else is left untouched, which keeps the screen compatible with mods such as Configured
 * and Catalogue.</p>
 */
public final class DollConfigScreen {
    /** Options whose tooltip should show nothing but the option name. */
    private static final Set<String> NO_DESCRIPTION = Set.of("enabled", "position", "rotationSensitivity");

    private DollConfigScreen() {}

    /**
     * {@code IConfigScreenFactory} implementation: builds the screen with our tooltip override.
     *
     * @param container the mod whose config is being edited
     * @param parent    the screen to return to
     * @return the configuration screen
     */
    public static Screen create(ModContainer container, Screen parent) {
        return new ConfigurationScreen(container, parent, Section::new);
    }

    /** Section screen that shows no tooltip at all for {@link #NO_DESCRIPTION}. */
    private static final class Section extends ConfigurationSectionScreen {
        Section(Screen parent, ModConfig.Type type, ModConfig config, Component title) {
            super(parent, type, config, title);
        }

        @Override
        protected Component getTooltipComponent(String key, ModConfigSpec.Range<?> range) {
            if (NO_DESCRIPTION.contains(key)) {
                // An empty component splits into zero tooltip lines, so no tooltip is drawn at all.
                return Component.empty();
            }
            return super.getTooltipComponent(key, range);
        }
    }
}
